"use server"

import { revalidatePath } from "next/cache"
import { z } from "zod"

import type { ApplicationStatus, OpportunityRow, OpportunityTrackingRow } from "@/src/lib/database.v2.types"
import { cleanText, isUuid } from "@/src/lib/validation"
import { fail, requireWorkspace, type ActionResult } from "@/src/lib/workspace"

const PATH = "/dashboard/opportunities"

export type Opportunity = Pick<
  OpportunityRow,
  | "id"
  | "title"
  | "organization"
  | "type"
  | "description"
  | "countries"
  | "industries"
  | "stages"
  | "funding_type"
  | "amount_text"
  | "eligibility"
  | "deadline"
  | "is_rolling"
  | "source_url"
  | "source_name"
  | "last_verified_at"
>

export type OpportunityTracking = Pick<OpportunityTrackingRow, "opportunity_id" | "bookmarked" | "application_status" | "notes">

const COLUMNS =
  "id, title, organization, type, description, countries, industries, stages, funding_type, amount_text, eligibility, deadline, is_rolling, source_url, source_name, last_verified_at"

/**
 * Published, verified opportunities. The catalogue is curated by platform
 * admins; nothing here is generated by AI.
 */
export async function listOpportunities(): Promise<{ opportunities: Opportunity[]; tracking: OpportunityTracking[] }> {
  const ws = await requireWorkspace("view")
  if ("error" in ws) return { opportunities: [], tracking: [] }

  const [{ data: opportunities }, { data: tracking }] = await Promise.all([
    ws.supabase
      .from("opportunities")
      .select(COLUMNS)
      .eq("status", "published")
      .order("deadline", { ascending: true, nullsFirst: false })
      .limit(500),
    ws.supabase
      .from("opportunity_tracking")
      .select("opportunity_id, bookmarked, application_status, notes")
      .eq("startup_id", ws.startup.id)
      .limit(500),
  ])
  return { opportunities: (opportunities ?? []) as Opportunity[], tracking: (tracking ?? []) as OpportunityTracking[] }
}

const trackingSchema = z
  .object({
    bookmarked: z.boolean(),
    applicationStatus: z.enum(["none", "preparing", "submitted", "accepted", "rejected"]),
    notes: z.string().max(2000),
  })
  .partial()

/** Saves a bookmark, application status or notes for the active business. */
export async function trackOpportunity(
  opportunityId: string,
  patch: { bookmarked?: boolean; applicationStatus?: ApplicationStatus; notes?: string },
): Promise<ActionResult<{ tracking: OpportunityTracking }>> {
  const parsed = trackingSchema.safeParse(patch)
  if (!isUuid(opportunityId) || !parsed.success) return fail("That opportunity is not available.")
  const ws = await requireWorkspace("edit")
  if ("error" in ws) return fail(ws.error)

  const { data: opportunity } = await ws.supabase.from("opportunities").select("id").eq("id", opportunityId).maybeSingle()
  if (!opportunity) return fail("That opportunity is no longer listed.")

  const { data: existing } = await ws.supabase
    .from("opportunity_tracking")
    .select("id, bookmarked, application_status, notes")
    .eq("startup_id", ws.startup.id)
    .eq("opportunity_id", opportunityId)
    .maybeSingle()

  const next = {
    bookmarked: parsed.data.bookmarked ?? existing?.bookmarked ?? true,
    application_status: parsed.data.applicationStatus ?? existing?.application_status ?? "none",
    notes: parsed.data.notes !== undefined ? cleanText(parsed.data.notes, 2000) : (existing?.notes ?? ""),
    updated_by: ws.user.id,
  }

  const query = existing
    ? ws.supabase.from("opportunity_tracking").update(next).eq("id", existing.id)
    : ws.supabase.from("opportunity_tracking").insert({ ...next, startup_id: ws.startup.id, opportunity_id: opportunityId })
  const { data, error } = await query.select("opportunity_id, bookmarked, application_status, notes").maybeSingle()
  if (error || !data) return fail("Could not save. Please try again.")

  revalidatePath(PATH)
  return { success: true, tracking: data as OpportunityTracking }
}
